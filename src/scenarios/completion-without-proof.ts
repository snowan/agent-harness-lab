function assertion(
  id: string,
  trialId: string,
  signal: AssertionSpec["signal"],
  title: string,
  factKey: string,
  equals: FactValue,
  passedMessage: string,
  failedMessage: string,
): AssertionSpec {
  return {
    id,
    trialId,
    signal,
    title,
    requirement: { factKey, equals },
    passedMessage,
    failedMessage,
  };
}

